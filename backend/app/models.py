class GuidelineRule(Base):
    __tablename__ = "guideline_rules"
    __table_args__ = (
        UniqueConstraint("org_id", "id"),
        UniqueConstraint("org_id", "code"),
        ForeignKeyConstraint(
            ["org_id", "guideline_id"], ["guideline_documents.org_id", "guideline_documents.id"], ondelete="CASCADE"
        ),
        Index("guideline_rules_tsv_idx", "tsv", postgresql_using="gin"),
    )

    id: Mapped[uuid.UUID] = _pk()
    org_id: Mapped[uuid.UUID] = mapped_column(Uuid, nullable=False)
    guideline_id: Mapped[uuid.UUID] = mapped_column(Uuid, nullable=False)
    code: Mapped[str] = mapped_column(Text, nullable=False)  # shown in citations, e.g. 'TONE-01'
    category: Mapped[str] = mapped_column(Text, nullable=False)  # tone | terminology | facts | visual | accessibility
    title: Mapped[str] = mapped_column(Text, nullable=False)
    body: Mapped[str] = mapped_column(Text, nullable=False)
    severity: Mapped[str] = mapped_column(Text, nullable=False, server_default="medium")  # low | medium | high
    page: Mapped[int | None] = mapped_column(Integer)
    embedding: Mapped[Any | None] = mapped_column(Vector(EMBEDDING_DIM))
    # generated by Postgres; never set it from Python
    tsv: Mapped[Any | None] = mapped_column(
        TSVECTOR, Computed("to_tsvector('english', title || ' ' || body)", persisted=True)
    )
    created_at: Mapped[datetime] = _created()


