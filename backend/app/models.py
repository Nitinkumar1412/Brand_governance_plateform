"""SQLAlchemy models. They mirror db/schema.sql, which is the source of truth.

Rules for this file:
  * Never call Base.metadata.create_all(). Tables come from schema.sql only.
  * CHECK constraints (source-or-silence, human sign-off, status values) live in the
    database, so they are not repeated here. A bad write raises IntegrityError.
  * If you change schema.sql, change the matching model in the same commit.
    tests/test_models_match_schema.py fails when the two disagree.
  * Relationships are read-only (viewonly). To write, set the ids and org_id
    explicitly; that keeps tenant rules visible in the code.
"""

import uuid
from datetime import date, datetime
from decimal import Decimal
from typing import Any

from pgvector.sqlalchemy import Vector
from sqlalchemy import (BigInteger,Date,Computed,DateTime,ForeignKey,ForeignKeyConstraint,Identity,Index,Integer,Numeric,REAL,Text,UniqueConstraint,Uuid,func,text,)

from sqlalchemy.dialects.postgresql import JSONB, TSVECTOR
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, relationship

EMBEDDING_DIM = 384  # BAAI/bge-small-en-v1.5. Must match vector(384) in schema.sql.


class Base(DeclarativeBase):
    pass


def _pk() -> Mapped[uuid.UUID]:
    return mapped_column(Uuid, primary_key=True, default=uuid.uuid4, server_default=text("gen_random_uuid()"))


def _created() -> Mapped[datetime]:
    return mapped_column(DateTime(timezone=True), nullable=False, server_default=func.now())


# 1. Accounts -----------------------------------------------------------------------


class Organization(Base):
    __tablename__ = "organizations"

    id: Mapped[uuid.UUID] = _pk()
    name: Mapped[str] = mapped_column(Text, nullable=False)
    created_at: Mapped[datetime] = _created()


class User(Base):
    __tablename__ = "users"
    __table_args__ = (UniqueConstraint("org_id", "id"),)

    id: Mapped[uuid.UUID] = _pk()
    org_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("organizations.id", ondelete="CASCADE"), nullable=False)
    email: Mapped[str] = mapped_column(Text, nullable=False, unique=True)
    full_name: Mapped[str] = mapped_column(Text, nullable=False)
    password_hash: Mapped[str] = mapped_column(Text, nullable=False)
    role: Mapped[str] = mapped_column(Text, nullable=False)  # admin | creator | reviewer
    created_at: Mapped[datetime] = _created()


